const I18nContext = createContext({
  language: 'ca',
  setLanguage: () => {},
  t: (key) => key
});

const interpolate = (template, variables = {}) =>
  Object.entries(variables).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template
  );

const getPluralKey = (key, count) => `${key}_${count === 1 ? 'one' : 'other'}`;

export const I18nProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => localStorage.getItem(LANGUAGE_STORAGE_KEY) || 'ca');

  useEffect(() => {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  }, [language]);

  const value = useMemo(() => {
    const t = (key, variables = {}) => {
      const activeTranslations = translations[language] || translations.ca;
      const rawValue = activeTranslations[key] ?? translations.ca[key] ?? key;
      return interpolate(rawValue, variables);
    };

    const tCount = (key, count, variables = {}) => t(getPluralKey(key, count), { count, ...variables });

    return { language, setLanguage, t, tCount, languages: translations };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export const useI18n = () => useContext(I18nContext);
